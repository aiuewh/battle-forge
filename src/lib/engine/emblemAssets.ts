// ============ 新增族类图标（2026-09-28 手绘，风格对齐恶魔.svg 的分层剪影） ============
// 数据在 emblemLayers.json：layers 为 viewBox 1024 下的分层 path（按绘制顺序 = z 序），
// base 为挤出主体层索引，其余为正面纹色薄片层。
import emblemLayersJson from './emblemLayers.json';

const NEW_EMBLEM_DEFS = emblemLayersJson as Record<
  string,
  {
    layers: Array<{ d: string; fill?: string }>;
    base: number[];
    /** 副色挤出层：base 索引 + 独立颜色（如兽人的黄色獠牙） */
    accent?: { base: number[]; color: string };
  }
>;

export function buildNewEmblem(kind: string): EmblemAsset {
  const def = NEW_EMBLEM_DEFS[kind];
  const solidIdx = new Set(def.base);
  if (def.accent) for (const i of def.accent.base) solidIdx.add(i);
  const asset: EmblemAsset = {
    vb: 1024,
    base: def.base.map(i => def.layers[i].d),
    detail: def.layers
      .map((layer, i) => ({ layer, i }))
      .filter(({ i }) => !solidIdx.has(i))
      .map(({ layer }) => ({ d: layer.d, fill: layer.fill ?? '#000000' })),
  };
  if (def.accent) {
    asset.accent = { base: def.accent.base.map(i => def.layers[i].d), color: def.accent.color };
  }
  return asset;
}

